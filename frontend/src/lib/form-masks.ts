// Маски и проверки для полей форм. Без сторонних библиотек — простые функции.
// Используются во всех формах сайта (контакты, страницы продуктов).

// Имя: оставляем только буквы (рус/англ), пробел и дефис.
// Удаляет цифры и любые спецсимволы — чтобы в поле "Имя" не вписали номер.
export function sanitizeName(value: string): string {
  return value.replace(/[^A-Za-zА-Яа-яЁё\s-]/g, "");
}

// Примечание: телефон теперь обрабатывает библиотека react-phone-number-input
// (международный формат + автоопределение страны), поэтому отдельных
// функций маски телефона здесь больше нет.

// Простая проверка email: что-то@что-то.домен
export function isValidEmail(value: string): boolean {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);
}
